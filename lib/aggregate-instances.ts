import type { EngineId } from './engines/types';
import { allEngines } from './engines/registry';
import type { ProviderId } from './providers/types';
import { allProviders } from './providers/registry';
import { isProviderInstanceId } from './provider-instances';
import type { AggregateInstanceId, AggregateMemberId } from './aggregate/types';
import { makeInstanceIdGuard, isBoundedInstanceCollection, normalizeInstanceCollection } from './normalize-instance-collection';
import { serializedSize } from './serialized-size';

export type { AggregateInstanceId, AggregateMemberId } from './aggregate/types';

/** Persisted aggregate instance record（R2）。空 members 合法存储（恒 ineligible → 实例隐藏）。 */
export interface AggregateInstance {
  id: AggregateInstanceId;
  /** 显示名：trim 后非空且 ≤ MAX_AGGREGATE_INSTANCE_NAME_LENGTH。 */
  name: string;
  /** 成员清单（AggregateMemberId[]）：存储序即扇出与答案展示序。 */
  members: AggregateMemberId[];
  /** 重排后保留条数，钳位 [MIN, MAX]；缺省由 clampAggregateTopN 物化为默认值。 */
  topN: number;
}

const AGGREGATE_ID_PREFIX = 'agg:';
/** Stable, storage-safe ids generated by the worker (UUIDs satisfy this form). 与 inst:/site: 同族。 */
const isAggregateIdForm = makeInstanceIdGuard(AGGREGATE_ID_PREFIX);

export const MAX_AGGREGATE_INSTANCES = 50;
export const MAX_AGGREGATE_INSTANCE_NAME_LENGTH = 40;
// Leaves ample room below the 256 KiB complete-import limit for the rest of the
// config while still bounding a persisted collection read from storage（与 provider/site 实例同值）。
export const MAX_AGGREGATE_SERIALIZED_BYTES = 128 * 1024;

export const MIN_AGGREGATE_TOP_N = 5;
export const MAX_AGGREGATE_TOP_N = 20;
export const DEFAULT_AGGREGATE_TOP_N = 20;

// 成员 id 存在性校验（能力无关）的 registry 派生源（不手写清单，避免与 union 漂移——
// derive-from-registry 先例）：只回答「这个 id 在 registry 里是否存在」，不回答「是否具备某能力」。
const PROVIDER_MEMBER_IDS: ReadonlySet<ProviderId> = new Set(allProviders().map((p) => p.id));
const ENGINE_MEMBER_IDS: ReadonlySet<string> = new Set(allEngines().map((e) => e.id));

export function isAggregateInstanceId(id: string): id is AggregateInstanceId {
  return isAggregateIdForm(id);
}

/** worker 生成新实例 id（UUID 满足 token 规则）。 */
export function newAggregateInstanceId(): AggregateInstanceId {
  return `agg:${crypto.randomUUID()}`;
}

/**
 * 成员 id 仅存在性校验（能力无关；KTD18/Oracle F6，措辞校准防误读）：provider 裸 id / engine id
 * 按 registry 存在性即收，provider 实例 id 按 id 形态（inst: 前缀 + token）即收。
 * 「engine 是否真带 extractor」等能力有效性在 eligibility 判定，normalize 不看 registry 能力，
 * 避免能力漂移悄悄改写存储成员清单。
 */
export function normalizeAggregateMemberId(value: unknown): AggregateMemberId | null {
  if (typeof value !== 'string') return null;
  if (PROVIDER_MEMBER_IDS.has(value as ProviderId)) return value as ProviderId;
  if ((ENGINE_MEMBER_IDS as ReadonlySet<string>).has(value)) return value as EngineId;
  if (isProviderInstanceId(value)) return value;
  return null;
}

/** topN 钳位（KTD18）：数值钳到 [5, 20]，缺省/非数 → DEFAULT（20）。 */
export function clampAggregateTopN(value: unknown): number {
  const n = typeof value === 'number' && Number.isFinite(value) ? Math.round(value) : DEFAULT_AGGREGATE_TOP_N;
  return Math.min(MAX_AGGREGATE_TOP_N, Math.max(MIN_AGGREGATE_TOP_N, n));
}

/** Validates and canonicalizes an untrusted persisted Aggregate Instance record. */
export function normalizeAggregateInstance(value: unknown): AggregateInstance | null {
  if (!value || typeof value !== 'object') return null;
  const candidate = value as Record<string, unknown>;
  if (typeof candidate.id !== 'string' || !isAggregateInstanceId(candidate.id)) return null;
  if (typeof candidate.name !== 'string' || !Array.isArray(candidate.members)) return null;
  const name = candidate.name.trim();
  if (!name || name.length > MAX_AGGREGATE_INSTANCE_NAME_LENGTH) return null;
  const seen = new Set<AggregateMemberId>();
  const members: AggregateMemberId[] = [];
  for (const item of candidate.members) {
    const member = normalizeAggregateMemberId(item);
    if (!member || seen.has(member)) continue;
    seen.add(member);
    members.push(member);
  }
  return { id: candidate.id, name, members, topN: clampAggregateTopN(candidate.topN) };
}

/**
 * Defensive storage normalization: invalid and repeated-id records are discarded
 * in first-seen order. Cap at MAX_AGGREGATE_INSTANCES.
 *
 * Trusted storage reads must never treat an oversized collection as empty — that
 * would let create/update/delete rewrite storage with a tiny array and wipe data.
 * Oversize-by-bytes still normalizes item-by-item; use isBoundedAggregateInstanceCollection
 * for untrusted import/config rejection（site-engine-third-source 安全持久化三不变量）。
 */
export function normalizeAggregateInstances(value: unknown): AggregateInstance[] {
  return normalizeInstanceCollection(value, normalizeAggregateInstance, MAX_AGGREGATE_INSTANCES);
}

/** Strict guard for untrusted import/config payloads (not trusted storage reads). */
export function isBoundedAggregateInstanceCollection(value: unknown): value is unknown[] {
  return isBoundedInstanceCollection(value, MAX_AGGREGATE_INSTANCES, MAX_AGGREGATE_SERIALIZED_BYTES);
}

export function aggregateInstancesSerializedBytes(value: unknown): number {
  return serializedSize(value);
}
