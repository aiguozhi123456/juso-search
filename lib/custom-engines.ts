// 自定义引擎（Custom Engine）：用户定义的任意搜索引擎，URL 模板含 %s 占位符。
//
// 与 site-instances.ts 同构：纯函数、无浏览器 API、防御式规范化。
// 区别：site-instance 把 site: 前缀注入已有引擎，custom-engine 直接导航到用户指定的 URL。

import { makeInstanceIdGuard, isBoundedInstanceCollection, normalizeInstanceCollection } from './normalize-instance-collection';
import { serializedSize } from './serialized-size';

/** IDs for user-defined custom search engines. */
export type CustomEngineId = `custom:${string}`;

/** Persisted Custom Engine record. `urlTemplate` must contain exactly one `%s`. */
export interface CustomEngineDefinition {
  id: CustomEngineId;
  name: string;
  urlTemplate: string;
}

const CUSTOM_ID_PREFIX = 'custom:';
/** Stable, storage-safe ids generated by the worker (UUIDs satisfy this form). */
const isCustomIdForm = makeInstanceIdGuard(CUSTOM_ID_PREFIX);

export const MAX_CUSTOM_ENGINES = 50;
export const MAX_CUSTOM_ENGINE_NAME_LENGTH = 40;
export const MAX_CUSTOM_ENGINE_URL_LENGTH = 2048;
// Leaves ample room below the 256 KiB complete-import limit for the rest of the
// config while still bounding a persisted collection read from storage.
export const MAX_CUSTOM_ENGINES_SERIALIZED_BYTES = 128 * 1024;

export function isCustomEngineId(id: string): id is CustomEngineId {
  return isCustomIdForm(id);
}

/**
 * %s 占位符的往返哨兵：URL 序列化器会对 % 百分号编码，解析前先换成哨兵、序列化后换回。
 * 模块级常量以便校验分支（拒绝含哨兵字面量的输入）与测试引用同一定义点。
 */
const QUERY_PLACEHOLDER_SENTINEL = 'JUSOQUERYPLACEHOLDER';

/**
 * Validates and canonicalizes a URL template string.
 * Must be a valid http(s) URL containing exactly one lowercase `%s` placeholder.
 * Rejects credentials and internal whitespace (mirrors site-instances normalizeSiteTarget).
 * Returns the canonical form (scheme+host lowercased) or null.
 */
export function normalizeCustomEngineUrlTemplate(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const input = value.trim();
  if (!input || input.length > MAX_CUSTOM_ENGINE_URL_LENGTH) return null;
  // Reject internal whitespace (same as site-instances).
  if (/\s/.test(input)) return null;

  // Must contain exactly one lowercase %s
  const matches = input.match(/%s/g);
  if (!matches || matches.length !== 1) return null;
  // String.replace（字符串模式）只换第一处：若模板本身含哨兵字面量，%s→哨兵 后会出现
  // 两处哨兵，回程 replace 只把第一处换回 %s，占位符静默迁移、模板被改写。序列化器
  // 不会凭空造出哨兵（host 一律小写），输入侧拒绝即可让单次替换安全。
  if (input.includes(QUERY_PLACEHOLDER_SENTINEL)) return null;

  // Parse with a sentinel so the URL serializer does not percent-encode the placeholder.
  let url: URL;
  try {
    url = new URL(input.replace('%s', QUERY_PLACEHOLDER_SENTINEL));
  } catch {
    return null;
  }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return null;
  // Reject credentials (mirrors site-instances.ts:77).
  if (url.username || url.password) return null;

  // Canonicalize: url.href has scheme+host lowercased by the URL serializer.
  const canonical = url.href.replace(QUERY_PLACEHOLDER_SENTINEL, '%s');
  if (canonical.length > MAX_CUSTOM_ENGINE_URL_LENGTH) return null;
  return canonical;
}

/** Validates and canonicalizes an untrusted persisted Custom Engine record. */
export function normalizeCustomEngineDefinition(value: unknown): CustomEngineDefinition | null {
  if (!value || typeof value !== 'object') return null;
  const candidate = value as Record<string, unknown>;
  if (typeof candidate.id !== 'string' || !isCustomEngineId(candidate.id)) return null;
  if (typeof candidate.name !== 'string') return null;
  const name = candidate.name.trim();
  if (!name || name.length > MAX_CUSTOM_ENGINE_NAME_LENGTH) return null;
  const urlTemplate = normalizeCustomEngineUrlTemplate(candidate.urlTemplate);
  if (!urlTemplate) return null;
  return { id: candidate.id, name, urlTemplate };
}

/**
 * Defensive storage normalization: invalid, repeated-id, and repeated-urlTemplate
 * records are discarded in first-seen order. Cap at MAX_CUSTOM_ENGINES.
 *
 * Trusted storage reads must never treat an oversized collection as empty — that
 * would let create/update/delete rewrite storage with a tiny array and wipe data.
 * Oversize-by-bytes still normalizes item-by-item; use isBoundedCustomEngineCollection
 * for untrusted import/config rejection.
 */
export function normalizeCustomEngineDefinitions(value: unknown): CustomEngineDefinition[] {
  return normalizeInstanceCollection(
    value,
    normalizeCustomEngineDefinition,
    MAX_CUSTOM_ENGINES,
    (definition) => definition.urlTemplate,
  );
}

/** Strict guard for untrusted import/config payloads (not trusted storage reads). */
export function isBoundedCustomEngineCollection(value: unknown): value is unknown[] {
  return isBoundedInstanceCollection(value, MAX_CUSTOM_ENGINES, MAX_CUSTOM_ENGINES_SERIALIZED_BYTES);
}

export function customEnginesSerializedBytes(value: unknown): number {
  return serializedSize(value);
}

/** Builds the navigation URL by replacing `%s` with the encoded query. */
export function buildCustomEngineUrl(urlTemplate: string, query: string): string {
  return urlTemplate.replace('%s', encodeURIComponent(query));
}

/** Lists duplicate urlTemplate groups in normalized definitions. */
export function findDuplicateCustomEngineUrls(definitions: readonly CustomEngineDefinition[]): { urlTemplate: string; ids: CustomEngineId[] }[] {
  const groups = new Map<string, CustomEngineId[]>();
  for (const definition of definitions) {
    const ids = groups.get(definition.urlTemplate) ?? [];
    ids.push(definition.id);
    groups.set(definition.urlTemplate, ids);
  }
  return [...groups.entries()]
    .filter(([, ids]) => ids.length > 1)
    .map(([urlTemplate, ids]) => ({ urlTemplate, ids }));
}

/**
 * Validates a content-script-supplied URL for the background `openNewTab` handler.
 *
 * Accepts only `http:`/`https:` and rejects credentials, mirroring
 * normalizeCustomEngineUrlTemplate. Every other scheme (chrome:, chrome-extension:,
 * javascript:, data:, file:, view-source:, …) is rejected. Returns the parsed
 * `url.href` — the same serialization used for navigation, so validation and
 * tabs.create operate on one canonical form — or null on any parse failure,
 * rejection, or over-length input.
 */
export function sanitizeOpenNewTabUrl(raw: string): string | null {
  if (typeof raw !== 'string' || raw.length > MAX_CUSTOM_ENGINE_URL_LENGTH + 4096) return null;
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    return null;
  }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return null;
  if (url.username || url.password) return null;
  return url.href;
}
