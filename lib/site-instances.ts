import type { EngineId, SearchEngine } from './engines/types';
import { getEngine } from './engines/registry';
import { isSerpUrl, isZhanneiSerpHostname } from './engines/scopes';
import { normalizeInstanceCollection } from './normalize-instance-collection';
import { serializedSize } from './serialized-size';

/** IDs for user-defined, site-scoped search sources. */
export type SiteInstanceId = `site:${string}`;

/** The engines which can express a site restriction. */
export type SiteInstanceEngineId = Extract<EngineId, 'google' | 'bing' | 'baidu'>;

/** baidu 的站内构造模式：zhannei = 真站内（zhannei.baidu.com）；query = 主站 `wd=site:host q` 前缀。 */
export type BaiduSiteConstruction = 'zhannei' | 'query';

/** bing 的站内构造模式：q1 = 高级关键字参数；query = `q=site:scope q` 前缀。 */
export type BingSiteConstruction = 'query' | 'q1';

export type SiteConstruction = BaiduSiteConstruction | BingSiteConstruction;

/** zhannei 模式筛选（仅 zhannei 模式生效；false/缺省不生成参数）。 */
export interface ZhanneiFilters {
  /** 时间范围（分钟）：60=1小时 / 1440=1天 / 10080=1周 / 43200=1月。 */
  timeRange?: 60 | 1440 | 10080 | 43200;
  /** `sort=lds` 按时间排序（缺省相关性）。 */
  sortByTime?: boolean;
  /** `stp=1` 仅标题（缺省全文）。 */
  titleOnly?: boolean;
}

export interface SiteInstanceOptions {
  mode?: BaiduSiteConstruction | BingSiteConstruction;
  zhannei?: ZhanneiFilters;
}

/** Persisted Site Instance record. `target` is always the normalized canonical URL. */
export interface SiteInstanceDefinition {
  id: SiteInstanceId;
  name: string;
  target: string;
  engineId: SiteInstanceEngineId;
  options?: SiteInstanceOptions;
}

/** Parsed form of a normalized target. Consumers should use this rather than parsing `target`. */
export interface NormalizedSiteTarget {
  /** Full canonical HTTP(S) URL, without a query string or fragment. */
  canonicalUrl: string;
  hostname: string;
  pathname: string;
}

export interface SiteInstanceQueryMatch {
  siteId: SiteInstanceId;
  baseQuery: string;
}

export interface DuplicateSiteInstanceScope {
  engineId: SiteInstanceEngineId;
  /** 构造模式（有效值，含读侧默认）。 */
  mode: SiteConstruction;
  scope: string;
  /** zhannei 筛选指纹（仅 zhannei 模式非空）。 */
  zhannei: string;
  siteIds: SiteInstanceId[];
}

const SITE_ID_PREFIX = 'site:';
/** Stable, storage-safe ids generated by the worker (UUIDs satisfy this form). */
const SITE_ID_TOKEN = /^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/;
const SITE_INSTANCE_ENGINE_IDS: ReadonlySet<string> = new Set(['google', 'bing', 'baidu']);
const BAIDU_CONSTRUCTIONS: ReadonlySet<string> = new Set(['zhannei', 'query']);
const BING_CONSTRUCTIONS: ReadonlySet<string> = new Set(['query', 'q1']);
const ZHANNEI_TIME_RANGES: ReadonlySet<number> = new Set([60, 1440, 10080, 43200]);
export const MAX_SITE_INSTANCES = 50;
export const MAX_INSTANCE_NAME_LENGTH = 40;
export const MAX_SITE_TARGET_LENGTH = 2048;
// Leaves ample room below the 256 KiB complete-import limit for the rest of the
// config while still bounding a persisted collection read from storage.
export const MAX_INSTANCES_SERIALIZED_BYTES = 128 * 1024;

export function isSiteInstanceId(id: string): id is SiteInstanceId {
  return id.startsWith(SITE_ID_PREFIX) && SITE_ID_TOKEN.test(id.slice(SITE_ID_PREFIX.length));
}

export function isSiteInstanceEngineId(id: string): id is SiteInstanceEngineId {
  return SITE_INSTANCE_ENGINE_IDS.has(id);
}

/** 读侧默认（legacy 无 options 记录）：baidu→zhannei（有意的行为变更）、bing→query（行为不变）。 */
export function legacyDefaultConstruction(engineId: SiteInstanceEngineId): SiteConstruction {
  return engineId === 'baidu' ? 'zhannei' : 'query';
}

/** 建侧默认（UI 表单初值 + 提交）：baidu→zhannei、bing→q1（用户确认的新默认）。 */
export function formDefaultConstruction(engineId: SiteInstanceEngineId): SiteConstruction {
  return engineId === 'baidu' ? 'zhannei' : engineId === 'bing' ? 'q1' : 'query';
}

function constructionsForEngine(engineId: SiteInstanceEngineId): ReadonlySet<string> {
  if (engineId === 'baidu') return BAIDU_CONSTRUCTIONS;
  if (engineId === 'bing') return BING_CONSTRUCTIONS;
  return new Set();
}

/** 解析定义的有效构造模式：options.mode 合法则用之，否则读侧默认；google 恒 'query'。 */
export function constructionFor(definition: Pick<SiteInstanceDefinition, 'engineId' | 'options'>): SiteConstruction {
  const mode = definition.options?.mode;
  if (typeof mode === 'string' && constructionsForEngine(definition.engineId).has(mode)) return mode;
  return legacyDefaultConstruction(definition.engineId);
}

/** zhannei 筛选指纹（固定字段序）：去重键的组成部分；非 zhannei 模式为空串。 */
export function zhanneiFingerprintFor(definition: Pick<SiteInstanceDefinition, 'engineId' | 'options'>): string {
  if (constructionFor(definition) !== 'zhannei') return '';
  const filters = definition.options?.zhannei;
  if (!filters) return '';
  return `${filters.timeRange ?? ''}|${filters.sortByTime === true ? 1 : 0}|${filters.titleOnly === true ? 1 : 0}`;
}

/**
 * options 严格白名单校验（KTD5）：非法值降级为默认而非整记录拒绝——
 * mode 不在 engine 允许集内 → 丢弃（落读侧默认）；timeRange 不在 4 枚举内 → 丢弃；
 * sortByTime/titleOnly 仅 `true` 物化；未知键忽略；google 带任何 options → 整体丢弃；
 * zhannei 筛选仅在有效构造为 zhannei 时物化。绝不把用户输入拼成任意 URL 参数。
 */
function normalizeSiteInstanceOptions(engineId: SiteInstanceEngineId, value: unknown): SiteInstanceOptions | undefined {
  if (engineId === 'google' || !value || typeof value !== 'object' || Array.isArray(value)) return undefined;
  const candidate = value as Record<string, unknown>;
  let mode: SiteConstruction | undefined;
  if (typeof candidate.mode === 'string' && constructionsForEngine(engineId).has(candidate.mode)) {
    mode = candidate.mode as SiteConstruction;
  }
  const effective: Pick<SiteInstanceDefinition, 'engineId' | 'options'> = { engineId, ...(mode ? { options: { mode } } : {}) };
  let zhannei: ZhanneiFilters | undefined;
  if (constructionFor(effective) === 'zhannei' && candidate.zhannei && typeof candidate.zhannei === 'object' && !Array.isArray(candidate.zhannei)) {
    const raw = candidate.zhannei as Record<string, unknown>;
    const filters: ZhanneiFilters = {};
    if (typeof raw.timeRange === 'number' && ZHANNEI_TIME_RANGES.has(raw.timeRange)) filters.timeRange = raw.timeRange as ZhanneiFilters['timeRange'];
    if (raw.sortByTime === true) filters.sortByTime = true;
    if (raw.titleOnly === true) filters.titleOnly = true;
    if (Object.keys(filters).length > 0) zhannei = filters;
  }
  const options: SiteInstanceOptions = {};
  if (mode) options.mode = mode;
  if (zhannei) options.zhannei = zhannei;
  return Object.keys(options).length > 0 ? options : undefined;
}

/**
 * Converts an entered site target to a safe canonical URL. Only HTTP(S) targets
 * are supported; credentials are deliberately rejected rather than retained.
 */
export function normalizeSiteTarget(value: unknown): NormalizedSiteTarget | null {
  if (typeof value !== 'string') return null;
  const input = value.trim();
  if (!input || input.length > MAX_SITE_TARGET_LENGTH || /\s/.test(input)) return null;

  const hasScheme = /^[a-zA-Z][a-zA-Z\d+.-]*:\/\//.test(input);
  const hasUnsupportedScheme = /^[a-zA-Z][a-zA-Z\d+.-]*:/.test(input) && !hasScheme;
  const isHostWithPort = /^[^/?#\s]+:\d+(?:[/?#]|$)/.test(input);
  if (hasUnsupportedScheme && !isHostWithPort) return null;
  if (hasScheme && !/^https?:\/\//i.test(input)) return null;
  if (!hasScheme && input.startsWith('//')) return null;

  let url: URL;
  try {
    url = new URL(hasScheme ? input : `https://${input}`);
  } catch {
    return null;
  }
  if ((url.protocol !== 'http:' && url.protocol !== 'https:') || !url.hostname || url.username || url.password) {
    return null;
  }
  // Strip trailing FQDN dots so site: scopes and duplicate detection treat
  // `docs.example.com.` the same as `docs.example.com` (validation alone is not enough).
  const hostname = url.hostname.replace(/\.+$/, '').toLowerCase();
  if (!isPublicHostname(hostname)) return null;
  try {
    url.hostname = hostname;
  } catch {
    return null;
  }

  url.search = '';
  url.hash = '';
  if (url.href.length > MAX_SITE_TARGET_LENGTH) return null;
  return { canonicalUrl: url.href, hostname: url.hostname, pathname: url.pathname };
}

/** Reject targets that could disclose a private network name to a public engine. */
function isPublicHostname(hostname: string): boolean {
  // Site restrictions are sent to third-party search engines.  A DNS lookup
  // here would be racy and still allow DNS rebinding, so the safe allow-list is
  // public-looking DNS names only -- never an address literal.
  const host = hostname.toLowerCase().replace(/\.+$/, '');
  if (!host || host.includes(':') || /^\d+(?:\.\d+)+$/.test(host)) return false;
  const labels = host.split('.');
  if (labels.length < 2 || host.length > 253 || labels.some((label) => !/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(label))) return false;

  const reservedSuffixes = ['localhost', 'local', 'internal', 'home', 'lan', 'test', 'invalid', 'example'];
  if (reservedSuffixes.some((suffix) => host === suffix || host.endsWith(`.${suffix}`))) return false;
  return host !== 'home.arpa' && !host.endsWith('.home.arpa');
}

/** Returns the engine-specific effective site scope for an already normalized target. */
export function siteScopeForTarget(engineId: SiteInstanceEngineId, target: NormalizedSiteTarget): string {
  switch (engineId) {
    case 'google': {
      // Google `site:` operands must not embed a scheme. Host-only when the path
      // is empty/root; otherwise hostname + pathname (trailing slash stripped).
      const path = target.pathname.replace(/\/+$/, '');
      return path ? `${target.hostname}${path}` : target.hostname;
    }
    case 'bing': {
      const segments = target.pathname.split('/').filter(Boolean).slice(0, 2);
      return segments.length === 0 ? target.hostname : `${target.hostname}/${segments.join('/')}`;
    }
    case 'baidu':
      return target.hostname;
  }
}

/** Returns a definition's effective scope, or null when its persisted target is invalid. */
export function siteScopeForDefinition(definition: Pick<SiteInstanceDefinition, 'engineId' | 'target'>): string | null {
  const target = normalizeSiteTarget(definition.target);
  return target ? siteScopeForTarget(definition.engineId, target) : null;
}

/** Validates and canonicalizes an untrusted persisted Site Instance record. */
export function normalizeSiteInstanceDefinition(value: unknown): SiteInstanceDefinition | null {
  if (!value || typeof value !== 'object') return null;
  const candidate = value as Record<string, unknown>;
  if (typeof candidate.id !== 'string' || !isSiteInstanceId(candidate.id)
    || typeof candidate.name !== 'string'
    || typeof candidate.engineId !== 'string' || !isSiteInstanceEngineId(candidate.engineId)) return null;
  const target = normalizeSiteTarget(candidate.target);
  const name = candidate.name.trim();
  const options = normalizeSiteInstanceOptions(candidate.engineId, candidate.options);
  return target && name && name.length <= MAX_INSTANCE_NAME_LENGTH
    ? { id: candidate.id, name, target: target.canonicalUrl, engineId: candidate.engineId, ...(options ? { options } : {}) }
    : null;
}

/** 去重键（KTD6）：(engineId, 有效构造模式, scope, zhannei 筛选指纹)。无效 target 返回 null。 */
function siteInstanceDedupKey(definition: SiteInstanceDefinition): string | null {
  const scope = siteScopeForDefinition(definition);
  if (!scope) return null;
  return [definition.engineId, constructionFor(definition), scope, zhanneiFingerprintFor(definition)].join('\u0000');
}

/**
 * Defensive storage normalization: invalid, repeated-id, and repeated dedup-key
 * (engine, mode, scope, zhannei 筛选) records are discarded in first-seen order.
 * Cap at MAX_SITE_INSTANCES.
 *
 * Trusted storage reads must never treat an oversized collection as empty — that
 * would let create/update/delete rewrite storage with a tiny array and wipe data.
 * Oversize-by-bytes still normalizes item-by-item; use isBoundedSiteInstanceCollection
 * for untrusted import/config rejection.
 */
export function normalizeSiteInstanceDefinitions(value: unknown): SiteInstanceDefinition[] {
  return normalizeInstanceCollection(value, normalizeSiteInstanceDefinition, MAX_SITE_INSTANCES, siteInstanceDedupKey);
}

/** Strict guard for untrusted import/config payloads (not trusted storage reads). */
export function isBoundedSiteInstanceCollection(value: unknown): value is unknown[] {
  return Array.isArray(value) && value.length <= MAX_SITE_INSTANCES && serializedSize(value) <= MAX_INSTANCES_SERIALIZED_BYTES;
}

/** UTF-8 JSON byte length of a value; Infinity when stringify fails. 口径见 lib/serialized-size.ts。 */
export function siteInstancesSerializedBytes(value: unknown): number {
  return serializedSize(value);
}

/** Builds the `site:`-prefixed query for a scope（query 模式构造与前缀识别共用）。 */
export function buildSiteScopeQuery(scope: string, baseQuery: string): string {
  return `site:${scope}${baseQuery ? ` ${baseQuery}` : ''}`;
}

/**
 * 按有效构造模式构建站内导航 URL：
 * - zhannei：`https://zhannei.baidu.com/cse/site?q=<q>&cc=<host>` + sti/sort/stp 筛选；
 * - q1：`https://www.bing.com/search?q=<q>&q1=site:<scope>`；
 * - query 模式 + google：底层引擎 `buildSerpUrl(buildSiteScopeQuery(scope, q))`（现状路径）。
 * target 无效返回 null。参数值全部经白名单/encodeURIComponent——绝不拼用户输入。
 */
export function buildSiteInstanceUrl(definition: Pick<SiteInstanceDefinition, 'engineId' | 'target' | 'options'>, baseQuery: string): string | null {
  const target = normalizeSiteTarget(definition.target);
  if (!target) return null;
  const scope = siteScopeForTarget(definition.engineId, target);
  const mode = constructionFor(definition);
  if (mode === 'zhannei') {
    const filters = definition.options?.zhannei;
    let url = `https://zhannei.baidu.com/cse/site?q=${encodeURIComponent(baseQuery)}&cc=${target.hostname}`;
    if (filters?.timeRange != null) url += `&sti=${filters.timeRange}`;
    if (filters?.sortByTime === true) url += '&sort=lds';
    if (filters?.titleOnly === true) url += '&stp=1';
    return url;
  }
  if (mode === 'q1') {
    return `https://www.bing.com/search?q=${encodeURIComponent(baseQuery)}&q1=${encodeURIComponent(`site:${scope}`)}`;
  }
  return getEngine(definition.engineId).buildSerpUrl(buildSiteScopeQuery(scope, baseQuery));
}

/**
 * Finds the saved definition that generated a query and returns the original
 * base query. A prefix only matches when it is complete or followed by exactly
 * the generated separating space, preventing partial-scope stripping.
 */
export function matchSiteInstanceQuery(
  engineId: SiteInstanceEngineId,
  query: string,
  definitions: readonly SiteInstanceDefinition[],
  activeSourceId?: string | null,
  sourceOrder?: readonly string[],
): SiteInstanceQueryMatch | null {
  const valid = definitions.flatMap((definition) => {
    if (definition.engineId !== engineId) return [];
    const scope = siteScopeForDefinition(definition);
    return scope ? [{ definition, prefix: buildSiteScopeQuery(scope, '') }] : [];
  });
  const byId = new Map(valid.map((entry) => [entry.definition.id, entry]));
  const ordered: typeof valid = [];
  const orderedIds = new Set<SiteInstanceId>();
  const add = (id: string | null | undefined) => {
    const entry = id ? byId.get(id as SiteInstanceId) : undefined;
    if (entry && !orderedIds.has(entry.definition.id)) {
      orderedIds.add(entry.definition.id);
      ordered.push(entry);
    }
  };
  add(activeSourceId);
  for (const id of sourceOrder ?? []) add(id);
  for (const entry of valid) add(entry.definition.id);

  for (const { definition, prefix } of ordered) {
    if (query === prefix) return { siteId: definition.id, baseQuery: '' };
    if (query.startsWith(`${prefix} `)) return { siteId: definition.id, baseQuery: query.slice(prefix.length + 1) };
  }
  return null;
}

/** 从 bing SERP 的 q1 参数提取首个 `site:` 操作数（引擎无关的 scope 文本），无则 null。 */
function siteOperandFromBingQ1(url: URL): string | null {
  const q1 = url.searchParams.get('q1');
  if (!q1) return null;
  const match = q1.match(/(?:^|\s)site:(\S+)/i);
  return match ? match[1] : null;
}

/**
 * 三路 SERP 上下文识别（KTD2）：识别按 `(engineId, scope)` 匹配、与构造模式无关——
 * 手输 `site:x q`（任意引擎）或手拼 `q1=site:x` 都能高亮实例并还原干净 baseQuery。
 * ① zhannei SERP：读 `cc`（host-only scope），匹配 engineId==='baidu' 的定义（跨模式）；
 * ② bing SERP 且有 `q1`：取首个 `site:` 操作数为 scope，匹配 engineId==='bing' 的定义（跨模式）；
 * ③ 前缀回退：raw query 的 `site:scope ` 前缀（保留 active-source-first / 完整前缀边界语义）。
 */
export function matchSiteInstanceFromUrl(
  engine: Pick<SearchEngine, 'id' | 'extractQuery'>,
  url: string,
  definitions: readonly SiteInstanceDefinition[],
  activeSourceId?: string | null,
  sourceOrder?: readonly string[],
): SiteInstanceQueryMatch | null {
  // ① zhannei：cc 即 host-only scope（URL 只解析一次）。
  let zhanneiParsed: URL | null = null;
  try {
    const candidate = new URL(url);
    if (isSerpUrl(candidate, isZhanneiSerpHostname, '/cse/site')) zhanneiParsed = candidate;
  } catch {
    // 非 URL / 解析失败 → 落到 bing q1 / 前缀路径。
  }
  if (zhanneiParsed) {
    const cc = zhanneiParsed.searchParams.get('cc')?.replace(/\.+$/, '').toLowerCase() ?? '';
    if (!cc) return null;
    const candidates = definitions.filter((definition) => definition.engineId === 'baidu' && siteScopeForDefinition(definition) === cc);
    const picked = pickByPreference(candidates, activeSourceId, sourceOrder);
    if (picked) return { siteId: picked.id, baseQuery: zhanneiParsed.searchParams.get('q') ?? '' };
    return null;
  }
  // ② bing q1：site: 操作数为 scope。
  if (engine.id === 'bing') {
    try {
      const parsed = new URL(url);
      const operand = siteOperandFromBingQ1(parsed);
      if (operand) {
        const candidates = definitions.filter((definition) => definition.engineId === 'bing' && siteScopeForDefinition(definition) === operand);
        const picked = pickByPreference(candidates, activeSourceId, sourceOrder);
        if (picked) return { siteId: picked.id, baseQuery: parsed.searchParams.get('q') ?? '' };
      }
    } catch {
      // URL 解析失败 → 落到前缀路径（extractQuery 也会失败返回 null）。
    }
  }
  // ③ 前缀回退：与构造模式解耦（前缀由各定义的 scope 生成）。
  const rawQuery = engine.extractQuery(url) ?? '';
  if (!rawQuery) return null;
  return isSiteInstanceEngineId(engine.id)
    ? matchSiteInstanceQuery(engine.id, rawQuery, definitions, activeSourceId, sourceOrder)
    : null;
}

/** active-source-first → sourceOrder → 首次出现（与 matchSiteInstanceQuery 的排序语义一致）。 */
function pickByPreference(
  candidates: readonly SiteInstanceDefinition[],
  activeSourceId?: string | null,
  sourceOrder?: readonly string[],
): SiteInstanceDefinition | null {
  if (candidates.length === 0) return null;
  const byActive = activeSourceId ? candidates.find((definition) => definition.id === activeSourceId) : undefined;
  if (byActive) return byActive;
  for (const id of sourceOrder ?? []) {
    const byOrder = candidates.find((definition) => definition.id === id);
    if (byOrder) return byOrder;
  }
  return candidates[0];
}

/** Lists duplicate dedup-key (engine, mode, scope, zhannei 筛选) groups in normalized definitions. */
export function findDuplicateSiteInstanceScopes(definitions: readonly SiteInstanceDefinition[]): DuplicateSiteInstanceScope[] {
  const groups = new Map<string, DuplicateSiteInstanceScope>();
  for (const definition of definitions) {
    const scope = siteScopeForDefinition(definition);
    if (!scope) continue;
    const mode = constructionFor(definition);
    const zhannei = zhanneiFingerprintFor(definition);
    const key = [definition.engineId, mode, scope, zhannei].join('\u0000');
    const group = groups.get(key) ?? { engineId: definition.engineId, mode, scope, zhannei, siteIds: [] };
    group.siteIds.push(definition.id);
    groups.set(key, group);
  }
  return [...groups.values()].filter((group) => group.siteIds.length > 1);
}
